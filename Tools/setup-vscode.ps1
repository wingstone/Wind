<#
.SYNOPSIS
    Generate .vscode/tasks.json and Wind.code-workspace from local.config.

.DESCRIPTION
    tasks.json and Wind.code-workspace contain machine-specific absolute paths.
    They are .gitignored and regenerated by this script from a template.

    First-time / new machine:
        Run: .\Tools\setup-vscode.ps1
        The script auto-detects UE 5.8, writes local.config, and generates
        the two VSCode files. On detection failure it tells you what to fill.

.PARAMETER ForceDetect
    Re-detect UE_ROOT and overwrite local.config even if it already exists.
#>
param(
    [switch]$ForceDetect
)

$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent

# ---- Read key=value config (ignore blanks and # comments) -----------------
function Read-Config([string]$path) {
    $cfg = [ordered]@{}
    foreach ($line in Get-Content $path -Encoding UTF8) {
        if ($line -match '^\s*([A-Z_]+)\s*=\s*(.+?)\s*$') {
            $cfg[$Matches[1]] = $Matches[2]
        }
    }
    return $cfg
}

# ---- Validate a UE 5.8 install root ---------------------------------------
function Test-UERoot([string]$path) {
    if (-not $path) { return $false }
    if (-not (Test-Path (Join-Path $path 'Engine\Build\BatchFiles\Build.bat'))) {
        return $false
    }
    $verFile = Join-Path $path 'Engine\Build\Build.version'
    if (Test-Path $verFile) {
        try {
            $v = Get-Content $verFile -Raw | ConvertFrom-Json
            return ($v.MajorVersion -eq 5 -and $v.MinorVersion -eq 8)
        } catch { return $false }
    }
    return $true
}

# ---- Auto-detect UE 5.8 root ----------------------------------------------
function Find-UERoot {
    if ($env:UE_ROOT -and (Test-UERoot $env:UE_ROOT)) {
        Write-Host "  detect: env UE_ROOT -> $env:UE_ROOT"
        return $env:UE_ROOT
    }
    foreach ($k in @(
        'HKLM:\SOFTWARE\EpicGames\Unreal Engine\5.8',
        'HKLM:\SOFTWARE\WOW6432Node\EpicGames\Unreal Engine\5.8'
    )) {
        try {
            $v = (Get-ItemProperty $k -ErrorAction Stop).InstalledDirectory
            if (Test-UERoot $v) { Write-Host "  detect: registry -> $v"; return $v }
        } catch {}
    }
    $manifest = Join-Path $env:ProgramData 'Epic\UnrealEngineLauncher\LauncherInstalled.dat'
    if (Test-Path $manifest) {
        try {
            $data = Get-Content $manifest -Raw | ConvertFrom-Json
            foreach ($entry in $data.InstallationList) {
                if ($entry.AppName -eq 'UE_5.8' -and (Test-UERoot $entry.InstallLocation)) {
                    Write-Host "  detect: LauncherInstalled.dat -> $($entry.InstallLocation)"
                    return $entry.InstallLocation
                }
            }
        } catch {}
    }
    try {
        $builds = Get-ItemProperty 'HKCU:\SOFTWARE\Epic Games\Unreal Engine\Builds' -ErrorAction Stop
        foreach ($prop in $builds.PSObject.Properties) {
            if ($prop.Name -like 'PS*') { continue }
            if (Test-UERoot $prop.Value) {
                Write-Host "  detect: HKCU\Builds -> $($prop.Value)"
                return $prop.Value
            }
        }
    } catch {}
    $drives = Get-PSDrive -PSProvider FileSystem | ForEach-Object { $_.Root.TrimEnd('\') }
    $patterns = @(
        'Program Files\Epic Games\UE_5.8',
        'ProgramFiles\Epic Games\UE_5.8',
        'Epic Games\UE_5.8',
        'Program\UE_5.8',
        'Games\UE_5.8',
        'UE_5.8'
    )
    foreach ($d in $drives) {
        foreach ($p in $patterns) {
            $candidate = Join-Path $d $p
            if (Test-UERoot $candidate) {
                Write-Host "  detect: path scan -> $candidate"
                return $candidate
            }
        }
    }
    return $null
}

# ---- Write local.config ---------------------------------------------------
function Write-LocalConfig([string]$ueRoot, [string]$projRoot) {
    $localPath = Join-Path $projRoot 'local.config'
    $content = @"
# Wind project - per-machine path configuration.
# This file is .gitignored and never committed.
# Generated/maintained by Tools\setup-vscode.ps1; you can also edit by hand.

# Unreal Engine 5.8 root (no trailing backslash)
UE_ROOT=$ueRoot

# Project root, i.e. directory that contains Wind.uproject
PROJECT_ROOT=$projRoot
"@
    [System.IO.File]::WriteAllText($localPath, $content, [System.Text.UTF8Encoding]::new($false))
    Write-Host "  wrote local.config"
}

# ---- Build the launch/debug config object (shared by all 8 launch tasks) --
function New-LaunchEntry {
    param(
        [string]$Name,
        [string]$Program,
        [string]$PreTask,
        [string[]]$ExtraArgs,
        [string]$Ue
    )
    return [ordered]@{
        name            = $Name
        request         = 'launch'
        program         = $Program
        preLaunchTask   = $PreTask
        args            = $ExtraArgs
        cwd             = $Ue
        stopAtEntry     = $false
        console         = 'integratedTerminal'
        type            = 'cppvsdbg'
        visualizerFile  = "$Ue\Engine\Extras\VisualStudioDebugging\Unreal.natvis"
        sourceFileMap   = [ordered]@{ 'D:\build\++UE5\Sync' = $Ue }
        sourceMap       = [ordered]@{ 'D:\build\++UE5\Sync' = $Ue }
    }
}

# ---- Generate .vscode/tasks.json ------------------------------------------
function Write-TasksJson([string]$ue, [string]$proj) {
    $uproject = Join-Path $proj 'Wind.uproject'

    $buildTasks = @()
    $configs = @('Debug','DebugGame','Development','Test','Shipping')
    $targets = @('Wind','WindEditor')

    foreach ($target in $targets) {
        foreach ($cfg in $configs) {
            $buildLabel = "$target Win64 $cfg Build"
            $cleanLabel = "$target Win64 $cfg Clean"

            $buildTasks += [ordered]@{
                label          = $buildLabel
                group          = 'build'
                type           = 'shell'
                command        = 'Engine\Build\BatchFiles\Build.bat'
                args           = @($target,'Win64',$cfg,$uproject,'-waitmutex')
                problemMatcher = '$msCompile'
                options        = [ordered]@{ cwd = $ue }
            }
            $buildTasks += [ordered]@{
                label          = "$target Win64 $cfg Rebuild"
                group          = 'build'
                type           = 'shell'
                command        = 'Engine\Build\BatchFiles\Build.bat'
                args           = @($target,'Win64',$cfg,$uproject,'-waitmutex')
                problemMatcher = '$msCompile'
                dependsOn      = @($cleanLabel)
                options        = [ordered]@{ cwd = $ue }
            }
            $buildTasks += [ordered]@{
                label          = $cleanLabel
                group          = 'build'
                type           = 'shell'
                command        = 'Engine\Build\BatchFiles\Clean.bat'
                args           = @($target,'Win64',$cfg,$uproject,'-waitmutex')
                problemMatcher = '$msCompile'
                options        = [ordered]@{ cwd = $ue }
            }
        }
    }

    $extraTasks = @(
        [ordered]@{
            label          = 'UE: Generate Project Files (VSCode)'
            detail         = 'Rebuild IntelliSense + VS Code project data with UBT. Run after adding/removing modules or editing *.Build.cs / *.Target.cs / *.uplugin.'
            type           = 'shell'
            command        = 'Engine\Build\BatchFiles\Build.bat'
            args           = @('-Mode=GenerateProjectFiles',"-Project=$uproject",'-VSCode')
            options        = [ordered]@{ cwd = $ue }
            problemMatcher = @()
        },
        [ordered]@{
            label          = 'UE: Build WindEditor Development'
            detail         = 'Incremental editor build. Fast verification loop for C++ changes.'
            group          = [ordered]@{ kind = 'build'; isDefault = $true }
            type           = 'shell'
            command        = 'Engine\Build\BatchFiles\Build.bat'
            args           = @('WindEditor','Win64','Development',$uproject,'-waitmutex')
            options        = [ordered]@{ cwd = $ue }
            problemMatcher = '$msCompile'
        },
        [ordered]@{
            label          = 'UE: Run Automation Tests (headless)'
            detail         = "Build, then run the Unreal automation test harness with no rendering and no UI. The filter is the test-name prefix 'Wind.' -- the trailing dot matters, because bare 'Wind' also matches engine tests such as Slate.Window.* . The harness exits non-zero both on test failure and when the filter matches nothing."
            type           = 'shell'
            command        = "$ue\Engine\Binaries\Win64\UnrealEditor-Cmd.exe"
            args           = @($uproject,'-ExecCmds=Automation RunTests Wind.;Quit','-unattended','-nopause','-nullrhi','-log','-stdout')
            options        = [ordered]@{ cwd = $ue }
            dependsOn      = 'UE: Build WindEditor Development'
            problemMatcher = @()
        }
    )

    $doc = [ordered]@{
        version = '2.0.0'
        tasks   = @($buildTasks + $extraTasks)
    }

    $json = $doc | ConvertTo-Json -Depth 10
    $outDir  = Join-Path $proj '.vscode'
    if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
    $outPath = Join-Path $outDir 'tasks.json'
    [System.IO.File]::WriteAllText($outPath, $json, [System.Text.UTF8Encoding]::new($false))
    Write-Host "  wrote .vscode\tasks.json"
}

# ---- Generate Wind.code-workspace -----------------------------------------
function Write-Workspace([string]$ue, [string]$proj) {
    $uproject = Join-Path $proj 'Wind.uproject'
    $dotnet   = "$ue\Engine\Binaries\ThirdParty\DotNet\10.0\win-x64"
    $binDir   = "$proj\Binaries\Win64"
    $ueBinDir = "$ue\Engine\Binaries\Win64"

    $launches = @(
        (New-LaunchEntry -Name 'Launch Wind (Debug)'       -Program "$binDir\UnrealGame-Win64-Debug.exe"       -PreTask 'Wind Win64 Debug Build'       -ExtraArgs @()         -Ue $ue),
        (New-LaunchEntry -Name 'Launch Wind (DebugGame)'   -Program "$binDir\UnrealGame-Win64-DebugGame.exe"   -PreTask 'Wind Win64 DebugGame Build'   -ExtraArgs @()         -Ue $ue),
        (New-LaunchEntry -Name 'Launch Wind (Development)' -Program "$binDir\UnrealGame.exe"                   -PreTask 'Wind Win64 Development Build' -ExtraArgs @()         -Ue $ue),
        (New-LaunchEntry -Name 'Launch Wind (Test)'        -Program "$binDir\UnrealGame-Win64-Test.exe"        -PreTask 'Wind Win64 Test Build'        -ExtraArgs @()         -Ue $ue),
        (New-LaunchEntry -Name 'Launch Wind (Shipping)'    -Program "$binDir\UnrealGame-Win64-Shipping.exe"    -PreTask 'Wind Win64 Shipping Build'    -ExtraArgs @()         -Ue $ue),
        (New-LaunchEntry -Name 'Launch WindEditor (Debug)'       -Program "$ueBinDir\UnrealEditor-Win64-Debug.exe"     -PreTask 'WindEditor Win64 Debug Build'       -ExtraArgs @($uproject) -Ue $ue),
        (New-LaunchEntry -Name 'Launch WindEditor (DebugGame)'   -Program "$ueBinDir\UnrealEditor-Win64-DebugGame.exe" -PreTask 'WindEditor Win64 DebugGame Build'   -ExtraArgs @($uproject) -Ue $ue),
        (New-LaunchEntry -Name 'Launch WindEditor (Development)' -Program "$ueBinDir\UnrealEditor.exe"                 -PreTask 'WindEditor Win64 Development Build' -ExtraArgs @($uproject) -Ue $ue)
    )

    $doc = [ordered]@{
        folders  = @(
            [ordered]@{ name = 'Wind'; path = '.' },
            [ordered]@{ name = 'UE5';  path = $ue  }
        )
        settings = [ordered]@{
            'js/ts.tsc.autoDetect'            = 'off'
            'npm.autoDetect'                  = 'off'
            'terminal.integrated.env.windows' = [ordered]@{
                PATH                     = "$dotnet;`${env:PATH}"
                DOTNET_ROOT              = $dotnet
                DOTNET_HOST_PATH         = "$dotnet\dotnet.exe"
                DOTNET_MULTILEVEL_LOOKUP = '0'
                DOTNET_ROLL_FORWARD      = 'LatestMajor'
            }
        }
        extensions = [ordered]@{
            recommendations = @('ms-vscode.cpptools','ms-dotnettools.csharp')
        }
        launch = [ordered]@{
            version        = '0.2.0'
            configurations = $launches
        }
    }

    $json = $doc | ConvertTo-Json -Depth 10
    $outPath = Join-Path $proj 'Wind.code-workspace'
    [System.IO.File]::WriteAllText($outPath, $json, [System.Text.UTF8Encoding]::new($false))
    Write-Host "  wrote Wind.code-workspace"
}

# ---- Main -----------------------------------------------------------------
$localPath = Join-Path $projectRoot 'local.config'
$local = if (Test-Path $localPath) { Read-Config $localPath } else { [ordered]@{} }

$needsDetect = $ForceDetect -or (-not (Test-UERoot $local['UE_ROOT']))

if ($needsDetect) {
    Write-Host 'Auto-detecting UE 5.8 install location...'
    $detected = Find-UERoot
    if (-not $detected) {
        Write-Error @"
Could not locate UE 5.8 automatically.
Create local.config (copy from local.config.example) and set:
    UE_ROOT=<folder that contains Engine\Build\BatchFiles\Build.bat>
    PROJECT_ROOT=$projectRoot
Or set the env var and rerun:  `$env:UE_ROOT = 'X:\path\to\UE_5.8'
"@
        exit 1
    }
    $local['UE_ROOT']      = $detected
    $local['PROJECT_ROOT'] = $projectRoot
    Write-LocalConfig $local['UE_ROOT'] $local['PROJECT_ROOT']
}

$ueRoot   = $local['UE_ROOT']
$projRoot = if ($local['PROJECT_ROOT']) { $local['PROJECT_ROOT'] } else { $projectRoot }

Write-Host "UE_ROOT      = $ueRoot"
Write-Host "PROJECT_ROOT = $projRoot"
Write-Host ''

Write-TasksJson $ueRoot $projRoot
Write-Workspace $ueRoot $projRoot

Write-Host ''
Write-Host 'Done. Open Wind.code-workspace in VSCode.'
